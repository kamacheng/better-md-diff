export type MessageKey = keyof typeof ENGLISH;
let language: Language = 'zh-CN';
const listeners = new Set<() => void>();
export function getLanguage(): Language { return language; }
export function languageForObsidian(code: string): Language { return /^zh(?:[-_]|$)/i.test(code) ? 'zh-CN' : 'en'; }
export function setLanguage(value: Language): void {
  if (language === value) return;
  language = value;
  for (const listener of listeners) listener();
}
export function onLanguageChange(listener: () => void): () => void { listeners.add(listener); return () => listeners.delete(listener); }
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const text = language === 'en' ? ENGLISH[key] : key;
  return text.replace(/\{(\w+)\}/g, (match: string, name: string) => values[name] === undefined ? match : String(values[name]));
}

/** Retain the key, not translated text, so already displayed errors switch immediately. */
export class LocalizedError extends Error {
  constructor(private key: MessageKey, private values: Record<string, string | number> = {}) { super(); }
  get message(): string { return t(this.key, this.values); }
}
